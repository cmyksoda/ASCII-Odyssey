"""Embed files as C byte arrays, each followed by a NUL so text files can be read as strings.

  embed.py OUT.c name=path [name=path ...]
"""
import sys


def main():
    out, pairs = sys.argv[1], sys.argv[2:]
    parts = ['// Generated by tools/embed.py. Do not edit.', '']
    for pair in pairs:
        name, path = pair.split('=', 1)
        data = open(path, 'rb').read() + b'\0'
        parts.append(f'const unsigned char {name}[{len(data)}] = {{')
        for i in range(0, len(data), 24):
            parts.append('    ' + ', '.join(str(b) for b in data[i:i + 24]) + ',')
        parts.append('};')
        parts.append(f'const unsigned int {name}_size = {len(data) - 1};')
        parts.append('')
    with open(out, 'w') as f:
        f.write('\n'.join(parts))


if __name__ == '__main__':
    main()
